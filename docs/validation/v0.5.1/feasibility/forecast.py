"""v0.5.1 WP1: the feasibility forecast (docs/plans/v0.5.1-plan.md, section 4).

A **diagnostic forecast**: it settles no target and is never an infeasibility record by itself.
Development data only. It orders the work and informs the maintainer.

- D1 EB1, EB2: 400 development binaries per family (seeds ``refute-v051-feas:<family>:<i>``),
  generated by the frozen C1 generator (``calib05.c1.generate``) and run through the frozen v0.5
  candidate generation (detrending, global prewhitening, search; the plans of
  ``calib05.plans.pair`` on the v0.4 claim's test plan). Eligibility, approximated: the search
  candidate's SNR at least the gate's ``min_snr`` (the final candidate and its gate test are not
  run, to keep the forecast inside its 4 processor-hours). For each eligible binary: the nearest
  planet at the found period (the C1 transit model; depth, impact parameter, epoch shift and the
  star's radius within 0.85 to 1.15 R_sun free; a seeded multi-start least-squares fit in white
  weights near the events), and the Mahalanobis distance ``d`` of the two noiseless curves under
  the generator's own noise (white plus the AR(1) of each sector, the exponential covariance of
  ``synthetic.ar1_series``; the trend left out, as if known). Optimistic survival
  ``1 - Phi(d - 1.645)``: as if a battery had a whole-battery false-failure rate of 0.05 on that
  nearest planet.
- D2, D4: 400 development planets (family P), eligible when the search SNR passes the gate and the
  candidate matches the truth (``c1.identity``). For each: the Cramer-Rao standard errors of the
  odd and even depths and of a phase-0.5 depth (the true trapezoid shape, the depths the only free
  parameters, the generator's noise), and whether #185's alternatives (the full depth for
  odd/even, the primary depth for the secondary) would be detectable (``alt / sigma >= 3 +
  1.645``).
- T2a: the v0.5 C2 records (development): among recovered gate-passing injections into
  original-gate-negative hosts, the fraction whose search SNR is below ``2 (3 + 1.645) = 9.29``,
  the SNR under which odd/even against the full depth cannot be detectable in white noise.
  **Deviation from the plan's wording** (each curve's white error): the C2 light curves are not
  cached, so the search SNR stands for it; recorded in the forecast's README.

Usage (heavy part; resumable: done tasks are skipped):
  scripts/launch_affinity.ps1 -Script docs/validation/v0.5.1/feasibility/forecast.py
      -Arguments 'run' -Log .cache/v051/feasibility/run
  .venv/Scripts/python.exe docs/validation/v0.5.1/feasibility/forecast.py summarize
"""

from __future__ import annotations

import hashlib
import json
import math
import sys
import time
from concurrent.futures import ProcessPoolExecutor, as_completed
from pathlib import Path
from statistics import NormalDist

import numpy as np

ROOT = Path(__file__).resolve().parents[4]
OUT = ROOT / ".cache/v051/feasibility"
RECORDS = OUT / "records.jsonl"
COST = OUT / "cost.jsonl"
HERE = Path(__file__).resolve().parent
SIZE = 400
FAMILIES = ("EB1", "EB2", "P")
Z = 3.0 + 1.645
TAU_DAYS = 1.0 / 24.0
C2_RECORDS = ROOT / ".cache/v05/calibration/c2/records.jsonl"


def seed(family: str, i: int) -> int:
    text = f"refute-v051-feas:{family}:{i}"
    return int(hashlib.sha256(text.encode()).hexdigest()[:16], 16)


# --- the noise covariance: white plus an exponential (AR(1)) term, per sector ---------------


def _precision_ou(t: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    """The tridiagonal precision of a unit-variance exponential covariance on times ``t``:
    (diagonal, off-diagonal)."""
    a = np.exp(-np.diff(t) / TAU_DAYS)
    w = 1.0 / (1.0 - a**2)
    diag = np.ones(t.size)
    diag[:-1] += a**2 * w
    diag[1:] += w - 1.0
    off = -a * w
    return diag, off


def mahalanobis2(t, sector, r, sigma_w, sigma_r):
    """``r^T Sigma^-1 r`` for Sigma = sigma_w^2 I + sigma_r^2 K, K exponential per sector."""
    from scipy.linalg import solve_banded

    if sigma_r <= 0:
        return float(np.sum(r**2) / sigma_w**2)
    total = 0.0
    for n in np.unique(sector):
        sel = sector == n
        ts, rs = t[sel], r[sel]
        if not np.any(rs):
            continue
        diag, off = _precision_ou(ts)
        # Sigma^-1 = (sigma_w^2 A + sigma_r^2 I)^-1 A, A the precision of K
        ar = diag * rs
        ar[:-1] += off * rs[1:]
        ar[1:] += off * rs[:-1]
        ab = np.zeros((3, ts.size))
        ab[0, 1:] = sigma_w**2 * off
        ab[1] = sigma_w**2 * diag + sigma_r**2
        ab[2, :-1] = sigma_w**2 * off
        x = solve_banded((1, 1), ab, ar)
        total += float(rs @ x)
    return total


# --- the planet model at the found period -----------------------------------------------------


def planet_model(t, period, t0, depth, b, radius):
    from refute.packs.tess import synthetic as syn
    from refute.packs.tess.calib05.c1 import a_over_rstar

    if depth <= 0:
        return np.zeros_like(t)
    k = math.sqrt(depth)
    a = a_over_rstar(period) / radius
    if (1 + k) ** 2 - b**2 <= 0:
        return np.zeros_like(t)
    total = period / math.pi * math.asin(min(1.0, math.sqrt((1 + k) ** 2 - b**2) / a))
    flat_arg = max(0.0, (1 - k) ** 2 - b**2)
    flat = period / math.pi * math.asin(min(1.0, math.sqrt(flat_arg) / a))
    ingress = (total - flat) / (2.0 * total)
    return syn.trapezoid(t, period, t0, depth, total, ingress)


def binary_model(t, truth):
    from refute.packs.tess import synthetic as syn

    p = truth.get("true_period_days", truth["period_days"])
    d, dur, f = truth["depth"], truth["duration_days"], truth["ingress_fraction"]
    r = truth["secondary_ratio"]
    m = syn.trapezoid(t, p, truth["t0_btjd"], d, dur, f)
    return m + syn.trapezoid(t, p, truth["t0_btjd"], r * d, dur, f, phase=0.5)


def nearest_planet(t, sector, truth, found):
    """The planet at the found period nearest to the binary (white weights near the events)."""
    from scipy.optimize import least_squares

    pf, t0f = found["period_days"], found["t0_btjd"]
    target = binary_model(t, truth)
    dt = np.mod(t - t0f + 0.5 * pf, pf) - 0.5 * pf
    near = np.abs(dt) <= 2.0 * truth["duration_days"]
    tn, yn = t[near], target[near]
    mean_depth = truth["depth"] * (1.0 + truth["secondary_ratio"]) / 2.0

    def resid(x):
        depth, b, shift, radius = x
        return planet_model(tn, pf, t0f + shift, depth, b, radius) - yn

    best = None
    for b0 in (0.0, 0.3, 0.6, 0.85):
        for r0 in (0.95, 1.05):
            for depth0 in (mean_depth, truth["depth"]):
                x0 = [depth0, b0, 0.0, r0]
                try:
                    fit = least_squares(
                        resid,
                        x0,
                        bounds=([1e-7, 0.0, -0.1, 0.85], [0.5, 1.2, 0.1, 1.15]),
                        x_scale=[mean_depth, 0.1, 0.005, 0.05],
                        max_nfev=400,
                    )
                except ValueError:
                    continue
                if best is None or fit.cost < best.cost:
                    best = fit
    depth, b, shift, radius = best.x
    r = planet_model(t, pf, t0f + shift, depth, b, radius) - target
    return {"depth": depth, "b": b, "shift": shift, "radius": radius}, r


# --- one task ---------------------------------------------------------------------------------


def run_one(family: str, i: int) -> dict:
    from refute.packs.tess import synthetic as syn
    from refute.packs.tess.calib05 import c1
    from refute.packs.tess.calib05.plans import pair
    from refute.packs.tess.calib05.steps import v04_test_plan
    from refute.packs.tess.detrend import detrend
    from refute.packs.tess.pipeline import global_prewhitening
    from refute.packs.tess.search import search_period

    started = time.process_time()
    s = seed(family, i)
    rec: dict = {"family": family, "index": i, "seed": str(s)}
    try:
        data, truth = c1.generate(family, s)
    except c1.GenerationFailedError as exc:
        rec.update(status="GENERATION_FAILURE", reason=str(exc))
        rec["cpu_seconds"] = time.process_time() - started
        return rec
    p04, _ = pair(v04_test_plan(ROOT))
    flat = detrend(data.lc, p04.detrend)
    pw, searched = global_prewhitening(data, p04, flat)
    cand = search_period(searched, p04.search).candidate
    found = None if cand is None else {"period_days": cand.period, "t0_btjd": cand.t0}
    snr = None if cand is None else float(cand.snr)
    eligible = snr is not None and snr >= p04.gauntlet.snr.min_snr
    if family == "P":
        eligible = eligible and c1.identity(truth, found)
    rec.update(status="OK", found=found, search_snr=snr, eligible=eligible)
    rec["truth"] = {
        k: truth.get(k)
        for k in (
            "period_days",
            "true_period_days",
            "depth",
            "secondary_ratio",
            "target_snr",
            "impact",
            "correlated",
            "sigma_white_ppm",
        )
    }
    t, sector = data.lc.time, data.lc.sector
    sigma_w = truth["sigma_white_ppm"] * 1e-6
    sigma_r = sigma_w / 2.0 if truth["correlated"] else 0.0
    if eligible and family in ("EB1", "EB2"):
        fit, r = nearest_planet(t, sector, truth, found)
        d = math.sqrt(mahalanobis2(t, sector, r, sigma_w, sigma_r))
        rec.update(nearest=fit, distance=d, survival=1.0 - NormalDist().cdf(d - 1.645))
    if eligible and family == "P":
        p, t0 = truth["period_days"], truth["t0_btjd"]
        unit = syn.trapezoid(t, p, t0, 1.0, truth["duration_days"], truth["ingress_fraction"])
        epoch = np.round((t - t0) / p).astype(int)
        odd = np.where(epoch % 2 != 0, unit, 0.0)
        even = np.where(epoch % 2 == 0, unit, 0.0)
        sec = syn.trapezoid(
            t, p, t0, 1.0, truth["duration_days"], truth["ingress_fraction"], phase=0.5
        )
        i_odd = mahalanobis2(t, sector, odd, sigma_w, sigma_r)
        i_even = mahalanobis2(t, sector, even, sigma_w, sigma_r)
        i_sec = mahalanobis2(t, sector, sec, sigma_w, sigma_r)
        depth = truth["depth"]
        sd_oe = math.sqrt(1 / i_odd + 1 / i_even) if i_odd > 0 and i_even > 0 else math.inf
        sd_sec = math.sqrt(1 / i_sec) if i_sec > 0 else math.inf
        rec.update(
            cr_sigma_odd_even=sd_oe,
            cr_sigma_secondary=sd_sec,
            odd_even_detectable=depth / sd_oe >= Z,
            secondary_detectable=depth / sd_sec >= Z,
        )
    rec["cpu_seconds"] = time.process_time() - started
    return rec


def _done() -> set[tuple[str, int]]:
    if not RECORDS.exists():
        return set()
    out = set()
    for line in RECORDS.read_text(encoding="utf-8").splitlines():
        if line.strip():
            r = json.loads(line)
            out.add((r["family"], int(r["index"])))
    return out


def run() -> None:
    from refute.core.runner import default_workers

    OUT.mkdir(parents=True, exist_ok=True)
    done = _done()
    tasks = [(f, i) for f in FAMILIES for i in range(SIZE) if (f, i) not in done]
    with ProcessPoolExecutor(max_workers=default_workers()) as pool:
        futures = {pool.submit(run_one, f, i): (f, i) for f, i in tasks}
        for fut in as_completed(futures):
            f, i = futures[fut]
            try:
                rec = fut.result()
            except Exception as exc:  # noqa: BLE001 - recorded, kept in the denominators
                rec = {"family": f, "index": i, "status": "ERROR", "reason": repr(exc)}
            with RECORDS.open("a", encoding="utf-8") as fh:
                fh.write(json.dumps(rec, sort_keys=True) + "\n")
            with COST.open("a", encoding="utf-8") as fh:
                fh.write(json.dumps({"task": f"{f}/{i}", "cpu": rec.get("cpu_seconds")}) + "\n")
    print("parent cpu seconds", time.process_time())


# --- summary ---------------------------------------------------------------------------------


def wilson_upper(k: int, n: int, z: float = 1.959964) -> float:
    p = k / n
    centre = (p + z * z / (2 * n)) / (1 + z * z / n)
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / (1 + z * z / n)
    return centre + half


def max_count(n: int) -> int:
    return max(k for k in range(n + 1) if wilson_upper(k, n) <= 0.10)


def poisson_binomial_cdf(p: np.ndarray, k: int) -> float:
    dist = np.zeros(p.size + 1)
    dist[0] = 1.0
    for q in p:
        dist[1:] = dist[1:] * (1 - q) + dist[:-1] * q
        dist[0] *= 1 - q
    return float(dist[: k + 1].sum())


def summarize() -> dict:
    recs = [json.loads(x) for x in RECORDS.read_text(encoding="utf-8").splitlines() if x.strip()]
    rng = np.random.default_rng(20261106)
    out: dict = {
        "label": "diagnostic forecast (v0.5.1 plan, section 4): it settles no target",
        "records": len(recs),
        "statuses": {},
    }
    for r in recs:
        out["statuses"][r["status"]] = out["statuses"].get(r["status"], 0) + 1
    for fam in ("EB1", "EB2"):
        rows = [r for r in recs if r["family"] == fam and r["status"] == "OK"]
        elig = [r for r in rows if r.get("eligible") and "survival" in r]
        s = np.array([r["survival"] for r in elig])
        n_conf = round(200 * len(elig) / max(len(rows), 1))
        k = max_count(n_conf)
        probs = []
        for _ in range(2000):
            sample = rng.choice(s, size=n_conf, replace=True)
            probs.append(poisson_binomial_cdf(sample, k))
        folded = sum(
            1
            for r in elig
            if abs(
                r["found"]["period_days"]
                / (r["truth"].get("true_period_days") or r["truth"]["period_days"])
                - 0.5
            )
            < 0.02
        )
        out[fam] = {
            "generated_ok": len(rows),
            "eligible": len(elig),
            "folded_at_half": folded,
            "expected_survival_fraction": float(s.mean()),
            "median_distance": float(np.median([r["distance"] for r in elig])),
            "c1_prime_eligible_projection": n_conf,
            "d1_max_survivors": k,
            "d1_expected_survivors_at_projection": float(s.mean() * n_conf),
            "d1_pass_probability_median": float(np.median(probs)),
            "d1_pass_probability_p95": float(np.percentile(probs, 95)),
        }
    rows = [r for r in recs if r["family"] == "P" and r["status"] == "OK"]
    elig = [r for r in rows if r.get("eligible") and "odd_even_detectable" in r]
    both = [r for r in elig if r["odd_even_detectable"] and r["secondary_detectable"]]
    hi = [r for r in elig if r["truth"]["target_snr"] >= 15]
    hi_not = [r for r in hi if not (r["odd_even_detectable"] and r["secondary_detectable"])]
    out["P"] = {
        "generated_ok": len(rows),
        "eligible": len(elig),
        "rule_can_be_detectable_fraction": len(both) / max(len(elig), 1),
        "odd_even_not_detectable": sum(not r["odd_even_detectable"] for r in elig),
        "secondary_not_detectable": sum(not r["secondary_detectable"] for r in elig),
        "d2_reference": "kept at least about 0.868 (the v0.5 C1 v0.4 value 0.968 minus 0.10)",
        "snr15_subset": len(hi),
        "snr15_not_detectable_fraction": len(hi_not) / max(len(hi), 1),
        "d4_reference": "INCONCLUSIVE at most 0.30",
    }
    if C2_RECORDS.exists():
        c2 = [json.loads(x) for x in C2_RECORDS.read_text(encoding="utf-8").splitlines() if x]
        out["T2a"] = _t2a(c2)
    return out


def _t2a(c2: list[dict]) -> dict:
    """Recovered gate-passing injections into original-gate-negative hosts (v0.5 C2)."""
    own = {
        r["target_key"]
        for r in c2
        if r["kind"] == "original" and r["status"] == "OK" and r["chain"]["v04"]["gate_passed"]
    }
    snrs = []
    for r in c2:
        if r["kind"] != "injection" or r["status"] != "OK" or r["target_key"] in own:
            continue
        rec = r.get("recovery") or r["chain"].get("recovery") or {}
        if not rec.get("recovered") or not rec.get("gate_passed"):
            continue
        cand = r["chain"]["v05"].get("candidate") or {}
        if cand.get("snr") is not None:
            snrs.append(float(cand["snr"]))
    below = sum(s < 2 * Z for s in snrs)
    return {
        "recovered_gate_passing": len(snrs),
        "search_snr_below_9_29": below,
        "fraction_below": below / max(len(snrs), 1),
        "t2a_reference": "survival at least about 0.897 (0.997 minus 0.10)",
    }


if __name__ == "__main__":
    if sys.argv[1:] == ["run"]:
        run()
    elif sys.argv[1:] == ["summarize"]:
        doc = summarize()
        (HERE / "forecast.json").write_text(
            json.dumps(doc, indent=1, sort_keys=True) + "\n", encoding="utf-8"
        )
        print(json.dumps(doc, indent=1, sort_keys=True))
    else:
        raise SystemExit("usage: forecast.py run|summarize")
